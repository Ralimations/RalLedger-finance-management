package com.ralledger.data.importing

import com.ralledger.domain.model.Account
import com.ralledger.domain.model.AccountType
import com.ralledger.domain.model.Category
import com.ralledger.domain.model.CategoryType
import com.ralledger.domain.model.Money
import com.ralledger.domain.model.TransactionType
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import java.nio.charset.StandardCharsets

class FinancialImportFileReaderTest {
    @Test
    fun detectsDelimitedAndStatementFormatsFromContentAndFileName() {
        assertEquals(
            FinancialImportFormat.TSV,
            FinancialImportFileReader.detectFormat("records.txt", "text/plain", "Date\tAmount\n2026-01-01\t1.00".toByteArray())
        )
        assertEquals(
            FinancialImportFormat.OFX,
            FinancialImportFileReader.detectFormat(null, "application/octet-stream", "<OFX><STMTTRN>".toByteArray())
        )
        assertEquals(
            FinancialImportFormat.QIF,
            FinancialImportFileReader.detectFormat("export.qif", null, "!Type:Bank\nD1/2/2026".toByteArray())
        )
        assertEquals(
            FinancialImportFormat.PDF,
            FinancialImportFileReader.detectFormat("statement.pdf", "application/pdf", "%PDF-1.7".toByteArray())
        )
        assertEquals(
            FinancialImportFormat.CSV,
            FinancialImportFileReader.detectFormat("statement.csv", "application/vnd.ms-excel", "Date,Amount\n2026-01-01,1.00".toByteArray())
        )
    }

    @Test
    fun detectsPreambleAndReadsEuropeanDebitCreditAmountsWithExplicitDefaults() {
        val text = "Statement for April\nGenerated by Example Bank\nDate;Debit;Credit;Description\n" +
            "2026-04-01;1.234,56;;Market\n2026-04-02;;25,00;Pay"
        val document = FinancialImportFileReader.parse("export.csv", "text/csv", text.toByteArray())
        assertEquals(listOf("Date", "Debit", "Credit", "Description"), document.table.headers)
        assertEquals(2, document.table.rows.size)

        val wallet = Account("wallet", "Wallet", accountType = AccountType.E_WALLET, currency = "EUR")
        val expense = Category("food", "Food", CategoryType.EXPENSE)
        val income = Category("salary", "Salary", CategoryType.INCOME)
        val mapping = TransactionCsvImporter.suggestMapping(document.table.headers).copy(
            defaultAccountId = wallet.id,
            defaultExpenseCategoryId = expense.id,
            defaultIncomeCategoryId = income.id
        )
        val preview = TransactionCsvImporter.preview(
            document.table, mapping, listOf(wallet), listOf(expense, income), emptyList(), emptyList()
        )

        assertEquals(2, preview.importableCount)
        assertEquals(0, preview.errorCount)
        assertEquals(TransactionType.EXPENSE, preview.transactions[0].transactionType)
        assertEquals(Money(123_456L), preview.transactions[0].amount)
        assertEquals(TransactionType.INCOME, preview.transactions[1].transactionType)
        assertEquals(Money(2_500L), preview.transactions[1].amount)
    }

    @Test
    fun decodesUtf16WithBom() {
        val payload = "Date,Amount\n2026-05-01,2.00".toByteArray(StandardCharsets.UTF_16LE)
        val bytes = byteArrayOf(0xFF.toByte(), 0xFE.toByte()) + payload
        val parsed = FinancialImportFileReader.parse("ledger.csv", "text/csv", bytes)

        assertEquals("Date", parsed.table.headers.first())
        assertEquals("2.00", parsed.table.rows.single().values[1])
    }

    @Test
    fun keepsFirstTransactionInHeaderlessCsvForManualMapping() {
        val parsed = FinancialImportFileReader.parse(
            "records.csv",
            "text/csv",
            "2026-07-01,Expense,12.50,Wallet,Food,Market\n2026-07-02,Income,25.00,Wallet,Salary,Pay".toByteArray()
        )

        assertEquals(listOf("Column 1", "Column 2", "Column 3", "Column 4", "Column 5", "Column 6"), parsed.table.headers)
        assertEquals(2, parsed.table.rows.size)
        assertEquals("2026-07-01", parsed.table.rows.first().values[0])
    }

    @Test
    fun parsesOfxIncomeAndKeepsStatementIdentifiersForDuplicateReview() {
        val ofx = """
            OFXHEADER:100
            <OFX><BANKTRANLIST>
            <STMTTRN><TRNTYPE>DEBIT<DTPOSTED>20260601120000<TRNAMT>-12.50<FITID>txn-1<NAME>Market<MEMO>Lunch</STMTTRN>
            <STMTTRN><TRNTYPE>CREDIT<DTPOSTED>20260602120000<TRNAMT>1500.00<FITID>txn-2<NAME>Employer<MEMO>Pay</STMTTRN>
            </BANKTRANLIST></OFX>
        """.trimIndent()
        val parsed = FinancialImportFileReader.parse("bank.ofx", null, ofx.toByteArray())

        assertEquals(FinancialImportFormat.OFX, parsed.format)
        assertEquals("2026-06-01", parsed.table.rows[0].values[0])
        assertEquals("Expense", parsed.table.rows[0].values[1])
        assertTrue(parsed.table.rows[0].values.last().contains("txn-1"))
        assertEquals("Income", parsed.table.rows[1].values[1])
    }

    @Test
    fun parsesQifTransfersAndRejectsSplitRowsFromAccidentalImport() {
        val qif = """
            !Type:Bank
            D6/3'26
            T-20.00
            PTransfer to savings
            L[Savings]
            ^
            D6/4/2026
            T-40.00
            PSplit purchase
            SFood
            $-20.00
            SHousehold
            $-20.00
            ^
            D6/5'26
            T-4.00
            PMarket
            LFood
            ^
        """.trimIndent()
        val parsed = FinancialImportFileReader.parse("bank.qif", null, qif.toByteArray())

        assertEquals(3, parsed.table.rows.size)
        assertEquals("Transfer", parsed.table.rows[0].values[1])
        assertEquals("Savings", parsed.table.rows[0].values[4])
        assertEquals("", parsed.table.rows[1].values[2])
        assertTrue(parsed.table.rows[1].values.last().contains("split"))

        val wallet = Account("wallet", "Wallet", accountType = AccountType.E_WALLET)
        val savings = Account("savings", "Savings", accountType = AccountType.PHYSICAL_SAVINGS)
        val food = Category("food", "Food", CategoryType.EXPENSE)
        val mapping = TransactionCsvImporter.suggestMapping(parsed.table.headers).copy(
            defaultAccountId = wallet.id,
            defaultDestinationAccountId = savings.id
        )
        val preview = TransactionCsvImporter.preview(
            parsed.table, mapping, listOf(wallet, savings), listOf(food), emptyList(), emptyList()
        )
        assertEquals(2, preview.importableCount)
        assertEquals(1, preview.errorCount)
        assertEquals(TransactionType.EXPENSE, preview.transactions[1].transactionType)
    }
}
